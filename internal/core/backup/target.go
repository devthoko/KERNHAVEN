package backup

import (
	"context"
	"crypto/rand"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// Target stores the repository's objects (AT-F14-02). Put makes an object
// visible only when it is complete.
type Target interface {
	Put(ctx context.Context, name string, r io.Reader) (int64, error)
	Get(ctx context.Context, name string) (io.ReadCloser, error)
	// List returns the objects below prefix (a directory, "snapshots/").
	List(ctx context.Context, prefix string) ([]ObjectInfo, error)
	// Delete removes an object; a missing object is not an error.
	Delete(ctx context.Context, name string) error
	Close() error
}

// ObjectInfo is one stored object.
type ObjectInfo struct {
	Name string
	Size int64
}

// ErrNotExist means the object does not exist on the target.
var ErrNotExist = errors.New("object does not exist")

// TargetError is a problem with the target's settings.
type TargetError struct{ Msg string }

func (e *TargetError) Error() string { return e.Msg }

func targetErr(format string, a ...any) error { return &TargetError{fmt.Sprintf(format, a...)} }

// Object names are generated by the Core; anything else is refused before
// it reaches a target.
var objectNameRe = regexp.MustCompile(`^(kernhaven-repo\.json|snapshots/[0-9A-Za-z-]{1,64}/(manifest|[0-9]{1,6})\.khb)$`)

func checkName(name string) error {
	if !objectNameRe.MatchString(name) {
		return fmt.Errorf("invalid object name %q", name)
	}
	return nil
}

var snapshotPrefixRe = regexp.MustCompile(`^snapshots/[0-9A-Za-z-]{1,64}/$`)

func checkPrefix(prefix string) error {
	if prefix != "snapshots/" && !snapshotPrefixRe.MatchString(prefix) {
		return fmt.Errorf("invalid prefix %q", prefix)
	}
	return nil
}

func tmpSuffix() string {
	b := make([]byte, 6)
	_, _ = rand.Read(b)
	return ".tmp-" + hex.EncodeToString(b)
}

// ---- local directory ----

// LocalConfig is a directory on a local disk.
type LocalConfig struct {
	Path string `json:"path"`
}

// CheckLocalPath requires an existing directory below one of roots, given
// without symbolic links, so a repository cannot point outside the
// directories the administrator allowed in core.toml.
func CheckLocalPath(p string, roots []string) error {
	if p == "" || !filepath.IsAbs(p) || filepath.Clean(p) != p {
		return targetErr("path must be an absolute, clean path")
	}
	inside := false
	for _, r := range roots {
		if rel, err := filepath.Rel(r, p); err == nil && rel != ".." && !strings.HasPrefix(rel, "../") {
			inside = true
			break
		}
	}
	if !inside {
		return targetErr("path must be inside one of the backup roots configured in core.toml: %s", strings.Join(roots, ", "))
	}
	real, err := filepath.EvalSymlinks(p)
	if err != nil {
		return targetErr("path %s does not exist", p)
	}
	if real != p {
		return targetErr("path must not contain symbolic links")
	}
	fi, err := os.Stat(p)
	if err != nil || !fi.IsDir() {
		return targetErr("path %s is not a directory", p)
	}
	return nil
}

type localTarget struct{ root *os.Root }

// OpenLocal opens a directory target. All access goes through os.Root, so
// object names cannot leave the directory even if they were not checked.
func OpenLocal(c LocalConfig, roots []string) (Target, error) {
	if err := CheckLocalPath(c.Path, roots); err != nil {
		return nil, err
	}
	r, err := os.OpenRoot(c.Path)
	if err != nil {
		return nil, err
	}
	return &localTarget{root: r}, nil
}

func (t *localTarget) Put(ctx context.Context, name string, r io.Reader) (int64, error) {
	if err := checkName(name); err != nil {
		return 0, err
	}
	if dir := path.Dir(name); dir != "." {
		if err := t.root.MkdirAll(dir, 0o700); err != nil {
			return 0, err
		}
	}
	tmp := name + tmpSuffix()
	f, err := t.root.OpenFile(tmp, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		return 0, err
	}
	n, err := io.Copy(f, ctxReader{ctx, r})
	if err == nil {
		err = f.Sync()
	}
	if cerr := f.Close(); err == nil {
		err = cerr
	}
	if err == nil {
		err = t.root.Rename(tmp, name)
	}
	if err != nil {
		_ = t.root.Remove(tmp)
		return n, err
	}
	if d, err := t.root.Open(path.Dir(name)); err == nil {
		_ = d.Sync()
		d.Close()
	}
	return n, nil
}

func (t *localTarget) Get(_ context.Context, name string) (io.ReadCloser, error) {
	if err := checkName(name); err != nil {
		return nil, err
	}
	f, err := t.root.Open(name)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, ErrNotExist
	}
	return f, err
}

func (t *localTarget) List(_ context.Context, prefix string) ([]ObjectInfo, error) {
	if err := checkPrefix(prefix); err != nil {
		return nil, err
	}
	var out []ObjectInfo
	err := fs.WalkDir(t.root.FS(), strings.TrimSuffix(prefix, "/"), func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			if errors.Is(err, fs.ErrNotExist) && p == strings.TrimSuffix(prefix, "/") {
				return fs.SkipAll
			}
			return err
		}
		if d.Type().IsRegular() && objectNameRe.MatchString(p) {
			fi, err := d.Info()
			if err != nil {
				return err
			}
			out = append(out, ObjectInfo{Name: p, Size: fi.Size()})
		}
		return nil
	})
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, err
}

func (t *localTarget) Delete(_ context.Context, name string) error {
	if err := checkName(name); err != nil {
		return err
	}
	err := t.root.Remove(name)
	if errors.Is(err, fs.ErrNotExist) {
		err = nil
	}
	if err == nil && strings.HasPrefix(name, "snapshots/") {
		_ = t.root.Remove(path.Dir(name)) // fails while the directory has entries
	}
	return err
}

func (t *localTarget) Close() error { return t.root.Close() }

// ctxReader stops long copies when ctx ends.
type ctxReader struct {
	ctx context.Context
	r   io.Reader
}

func (c ctxReader) Read(p []byte) (int, error) {
	if err := c.ctx.Err(); err != nil {
		return 0, err
	}
	return c.r.Read(p)
}
